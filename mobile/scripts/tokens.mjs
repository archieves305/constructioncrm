// The app's colours come from the web's design tokens (src/app/globals.css),
// converted from oklch to the hex React Native takes. `node scripts/tokens.mjs`
// rewrites src/ui/tokens.ts; a CRM test (src/lib/mobile-api/tokens.test.ts)
// fails when the two drift, so a token change on the web reaches the phone.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const CSS_PATH = join(HERE, "../../src/app/globals.css");
export const OUT_PATH = join(HERE, "../src/ui/tokens.ts");

function block(css, selector) {
  const i = css.indexOf(`${selector} {`);
  if (i < 0) throw new Error(`no ${selector} block`);
  return css.slice(i, css.indexOf("\n}", i));
}

function vars(text) {
  const out = {};
  for (const m of text.matchAll(/--([a-z0-9-]+):\s*(oklch\([^)]*\))/g)) out[m[1]] = m[2];
  return out;
}

/** oklch(L C h [/ a]) → #RRGGBB or #RRGGBBAA (sRGB, clamped). */
export function oklchToHex(value) {
  const m = value.match(/oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+)(%?))?\s*\)/);
  if (!m) throw new Error(`not oklch: ${value}`);
  const [L, C, H] = [Number(m[1]), Number(m[2]), (Number(m[3]) * Math.PI) / 180];
  const a = C * Math.cos(H), b = C * Math.sin(H);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const mm = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * mm + 1.707614701 * s,
  ];
  const enc = (x) => {
    const c = Math.min(1, Math.max(0, x));
    const v = c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055;
    return Math.round(v * 255).toString(16).padStart(2, "0").toUpperCase();
  };
  let hex = "#" + lin.map(enc).join("");
  if (m[4] !== undefined) {
    const alpha = m[5] ? Number(m[4]) / 100 : Number(m[4]);
    hex += Math.round(alpha * 255).toString(16).padStart(2, "0").toUpperCase();
  }
  return hex;
}

const TONES = ["neutral", "info", "warning", "danger", "success"];

export function buildTokens(css) {
  const light = vars(block(css, ":root"));
  const dark = { ...light, ...vars(block(css, ".dark")) };
  const pick = (v, name, fallback) => oklchToHex(v[name] ?? v[fallback]);
  const scheme = (v, isDark) => ({
    bg: isDark ? pick(v, "background") : pick(v, "surface-muted"),
    card: pick(v, "card"),
    text: pick(v, "foreground"),
    muted: pick(v, "muted-foreground"),
    // The stronger web border: a phone is read outdoors, where the light one vanishes.
    border: isDark ? pick(v, "border") : pick(v, "border-strong", "border"),
    brand: pick(v, "brand"),
    brandText: isDark ? pick(v, "background") : "#FFFFFF",
    brandSoft: pick(v, "brand-soft"),
    brandFg: pick(v, "brand-fg"),
    danger: pick(v, "tone-danger-fg"),
    warn: pick(v, "tone-warning-fg"),
    ok: pick(v, "tone-success-fg"),
    tones: Object.fromEntries(TONES.map((t) => [t, { soft: pick(v, `tone-${t}-soft`), fg: pick(v, `tone-${t}-fg`), dot: pick(v, `tone-${t}`) }])),
  });
  const body = JSON.stringify({ light: scheme(light, false), dark: scheme(dark, true) }, null, 2).replace(/"([a-zA-Z]+)":/g, "$1:");
  return `// Generated by mobile/scripts/tokens.mjs from src/app/globals.css. Do not edit:\n// change the web token and run \`node scripts/tokens.mjs\` in mobile/.\nexport const TOKENS = ${body} as const;\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT_PATH, buildTokens(readFileSync(CSS_PATH, "utf8")));
  console.log(`wrote ${OUT_PATH}`);
}
